import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { mkdirSync, createWriteStream } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { electronSwitches, launchArguments } from '../lib/launch.mjs';
import { selectRuntime } from '../lib/runtime.mjs';
import { graphicsEnvironment } from '../lib/graphics.mjs';
const require = createRequire(import.meta.url);
const bundledBinary = require('electron');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
mkdirSync(resolve(root, 'artifacts'), { recursive: true });
const log = createWriteStream(resolve(root, 'artifacts/startup.log'), { flags: 'w' });
const args = launchArguments(process.argv.slice(2), process.env);
const env = graphicsEnvironment(args, { ...process.env, COMPANION_GRAPHICS: process.env.COMPANION_GRAPHICS || (process.platform === 'linux' ? 'nvidia' : 'auto') });
delete env.ELECTRON_RUN_AS_NODE;
console.log('Starting Live2D controls. Diagnostics: artifacts/startup.log');
const binary = selectRuntime(args, env, bundledBinary);
const nativeFlags = electronSwitches(args, env);
console.log('[launcher] Electron runtime:', binary);
console.log('[launcher] Native flags:', nativeFlags.join(' '));
console.log('[launcher] Desktop:', JSON.stringify({ display: env.DISPLAY, waylandDisplay: env.WAYLAND_DISPLAY, session: env.XDG_SESSION_TYPE }));
const child = spawn(binary, [...nativeFlags, resolve(root, 'electron/main.mjs'), ...args], { cwd: root, env, stdio: ['inherit', 'pipe', 'pipe'] });
child.stdout.on('data', data => { process.stdout.write(data); log.write(data); });
child.stderr.on('data', data => { process.stderr.write(data); log.write(data); });
child.on('error', error => { console.error(error.message); log.end(error.message); process.exitCode = 1; });
child.on('exit', (code, signal) => {
  if (signal || code) console.error(`Electron exited: ${signal || code}`);
  log.end(); process.exitCode = code ?? 1;
});
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
